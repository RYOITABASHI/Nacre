"""Generate ime-core/src/main/assets/dict/person_names.tsv.

NacreDictionary.loadSupplementaryDict("dict/person_names.tsv", ...) has always
expected this file, but it was never committed, so person-name entries were
silently skipped at load. This script builds it from generic, nationally
common Japanese names only:

  * Surnames: the published national surname ranking (名字由来net
    "全国名字ランキング", Rixsta) — the top 100 in published order, followed
    by the commonly published next band. One entry per surname with its
    dominant reading; a second entry where another reading is also common
    (e.g. 山崎 やまさき, 河野 かわの).
  * Given names: names that top the published baby-name surveys of
    Meiji Yasuda Life ("赤ちゃんの名前調査", running since 1989), pooled
    across eras so the list covers living adults as well as recent children
    (classic 太郎/花子/一郎 through modern 陽翔/紬/凛). 表記・読み pairs are
    the surveys' published top spellings/readings.
  * Full names: every surname x given-name combination, reading =
    surname reading + given reading, surface = surname + given. This is
    what makes a typed full name convert in one shot instead of relying on
    segmentation luck.

No individual's data is included: every entry is a nationally common name
taken from the published rankings above.

Output format (must match NacreDictionary.loadSupplementaryDict):
    reading<TAB>surface<TAB>left_id<TAB>right_id<TAB>cost
POS IDs and base costs follow the convention already used by
.github/workflows/build-person-names.yml (the JMnedict-based generator that
was never shipped): 1921 = full name, 1922 = given name, 1923 = surname.
Note NacreDictionary additionally subtracts 1500 from entries with
left_id in 1921..1923 and cost > 3500 at load time, so the effective costs
are 2500 / 3500 / 3000 respectively.

Usage: python3 tools/dict/generate_person_names.py
Writes ime-core/src/main/assets/dict/person_names.tsv (path resolved
relative to this script). Deterministic: same input lists -> same file.
"""

