# Mozc POS IDs / base costs (same convention as build-person-names.yml).
POS_FULL, COST_FULL = 1921, 4000
POS_GIVEN, COST_GIVEN = 1922, 5000
POS_SURNAME, COST_SURNAME = 1923, 4500


def main() -> None:
    surnames = list(dict.fromkeys(SURNAMES))  # dedupe, keep order
    given = list(dict.fromkeys(GIVEN_NAMES_MALE + GIVEN_NAMES_FEMALE))

    lines: list[str] = []
    seen: set[tuple[str, str]] = set()

    def emit(reading: str, surface: str, pos: int, cost: int) -> None:
        if (reading, surface) in seen:
            return
        seen.add((reading, surface))
        lines.append(f"{reading}\t{surface}\t{pos}\t{pos}\t{cost}")

    for surface, reading in surnames:
        emit(reading, surface, POS_SURNAME, COST_SURNAME)
    n_surname = len(lines)

    for surface, reading in given:
        emit(reading, surface, POS_GIVEN, COST_GIVEN)
    n_given = len(lines) - n_surname

    for s_surface, s_reading in surnames:
        for g_surface, g_reading in given:
            emit(s_reading + g_reading, s_surface + g_surface,
                 POS_FULL, COST_FULL)
    n_full = len(lines) - n_surname - n_given

    header = (
        "# Person name dictionary: common Japanese surnames, given names,\n"
        "# and composed full names (surname x given name).\n"
        "# Generated by tools/dict/generate_person_names.py - do not edit\n"
        "# by hand; edit the source lists in that script and re-run it.\n"
        "# Sources and method: person_names_NOTES.md in this directory.\n"
        "# Format: reading\\tsurface\\tleft_id\\tright_id\\tcost\n"
        "# POS (Mozc IDs): 1921=full name, 1922=given name, 1923=surname.\n"
        f"# Entries: {len(lines)} (surnames {n_surname}, "
        f"given names {n_given}, full names {n_full})\n"
    )

    out = (Path(__file__).resolve().parents[2]
           / "ime-core/src/main/assets/dict/person_names.tsv")
    out.write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out}: {len(lines)} entries "
          f"(surnames {n_surname}, given {n_given}, full {n_full})")


if __name__ == "__main__":
    main()
